'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {setup,command}=require('./helpers/v2-treatment');
const {ChainAuth}=require('../src/v2/chain-auth');
const {ChainClinicalQuery}=require('../src/v2/chain-clinical-query');
const {insert,fact}=require('../src/v2/common');

test('真实会话、岗位资格和跨店授权共同校验，身份与时间取自服务端',t=>{
 const a=setup(t), db=a.db;
 const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64');
 const document=a.documents.upload(a.d,command({...a.context,documentType:'影像',source:'演示设备',ownershipNote:'核实演示就诊',reason:'演示归档',originalName:'演示影像.png',contentBase64:png.toString('base64')}));
 db.exec('ALTER TABLE visit ADD COLUMN branch_id INTEGER; ALTER TABLE health_version ADD COLUMN source_visit_id INTEGER REFERENCES visit(id); CREATE UNIQUE INDEX candidate_visit_scope ON visit(id,patient_id,branch_id)');
 db.prepare('UPDATE visit SET branch_id=1 WHERE id=?').run(a.v.id);
 const ddl=fs.readFileSync(path.resolve(__dirname,'../../../01-需求文档/设计交付/连锁基础表候选结构.sql'),'utf8');
 db.exec(ddl);
 const now=a.auth.now(), dentist=a.auth.session(a.d.token).staff_id, manager=a.auth.session(a.m.token).staff_id;
 db.exec("INSERT INTO clinic_chain(id,name) VALUES(1,'演示连锁'); INSERT INTO clinic_branch(id,chain_id,branch_code,name) VALUES(1,1,'A','一店'),(2,1,'B','二店')");
 db.prepare('INSERT INTO branch_staff_role(branch_id,staff_id,role_code,valid_from,granted_by,granted_at,evidence) VALUES(2,?,?,?,?,?,?)').run(dentist,'dentist','2026-10-01T00:00:00Z',manager,now,'演示授权');
 db.prepare('INSERT INTO cross_branch_record_access(dentist_id,patient_id,visit_id,source_branch_id,target_branch_id,scope,valid_from,granted_by,granted_at,evidence) VALUES(?,?,?,1,2,?,?,?,?,?)').run(dentist,1,a.v.id,'record','2026-10-01T00:00:00Z',manager,now,'演示授权');
 const service=new ChainAuth(a.auth), request={targetBranchId:2,sourceBranchId:1,patientId:1,visitId:a.v.id,scope:'record',staffId:999,at:'2099-01-01T00:00:00Z'};
 const gateway=new ChainClinicalQuery(a.auth,a.documentStore);
 assert.equal(service.authorizeCrossBranchRead(a.d,request).session.staff_id,dentist);
 assert.equal(gateway.read(a.d,request).record.visit_id,a.v.id);
 assert.throws(()=>gateway.read(a.d,{...request,scope:'health'}),/无权/);
 const audit=db.prepare("SELECT event_type,outcome_code,authority_snapshot FROM operation_audit WHERE object_kind='cross_branch_clinical' ORDER BY id").all();
 assert.deepEqual(audit.map(r=>r.outcome_code),['CROSS_BRANCH_QUERY_OK','CROSS_BRANCH_FORBIDDEN']);
 assert.equal(JSON.parse(audit[0].authority_snapshot).visitId,a.v.id);
 assert.equal(JSON.parse(audit[1].authority_snapshot).scope,'health');
 db.exec("CREATE TEMP TRIGGER candidate_fail_audit BEFORE INSERT ON operation_audit BEGIN SELECT RAISE(ABORT,'audit unavailable'); END");
 assert.throws(()=>gateway.read(a.d,request),/audit unavailable/);
 db.exec('DROP TRIGGER candidate_fail_audit');
 db.prepare('INSERT INTO cross_branch_record_access(dentist_id,patient_id,visit_id,source_branch_id,target_branch_id,scope,valid_from,granted_by,granted_at,evidence) VALUES(?,?,?,1,2,?,?,?,?,?)').run(dentist,1,a.v.id,'health','2026-10-01T00:00:00Z',manager,now,'演示授权');
 const fields={patient_id:1,formed_at:now,change_reason:'演示',effective_at:now,created_by:dentist,previous_version_id:null};
 const known=insert(db,'health_version',fact(now,{...fields,version_no:1,source_visit_id:a.v.id}));
 insert(db,'health_version',fact(now,{...fields,version_no:2,source_visit_id:null}));
 insert(db,'health_item',fact(now,{health_version_id:known,category:'过敏',content:'演示未知',certainty:'未知',reported_at:now,source:'演示患者',occurred_at:null}));
 const health=gateway.read(a.d,{...request,scope:'health'});
 assert.deepEqual(health.versions.map(v=>v.id),[known]);assert.equal(health.versions[0].items[0].certainty,'未知');
 assert.throws(()=>gateway.read(a.d,{...request,patientId:999}),/无权/);
 assert.throws(()=>gateway.read(a.f,request),/无权/);
 const docRequest={...request,scope:'document',documentVersionId:document.id};
 assert.throws(()=>gateway.read(a.d,docRequest),/无权/);
 db.prepare('INSERT INTO cross_branch_record_access(dentist_id,patient_id,visit_id,source_branch_id,target_branch_id,scope,valid_from,granted_by,granted_at,evidence) VALUES(?,?,?,1,2,?,?,?,?,?)').run(dentist,1,a.v.id,'document','2026-10-01T00:00:00Z',manager,now,'演示授权');
 const file=gateway.read(a.d,docRequest);assert.deepEqual(file.bytes,png);assert.equal(file.documentVersionId,document.id);assert.equal('storage_key' in file,false);
 db.exec("CREATE TEMP TRIGGER candidate_document_audit_failure BEFORE INSERT ON operation_audit BEGIN SELECT RAISE(ABORT,'document audit unavailable'); END");
 assert.throws(()=>gateway.read(a.d,docRequest),/document audit unavailable/);
 db.exec('DROP TRIGGER candidate_document_audit_failure');
 assert.throws(()=>gateway.read(a.d,{...docRequest,documentVersionId:99999}),/未找到/);
 const stored=db.prepare('SELECT storage_key FROM document_version WHERE id=?').get(document.id).storage_key;
 a.documentStore.memory.set(stored,Buffer.from('损坏'));
 assert.throws(()=>gateway.read(a.d,docRequest),/校验不符/);
 a.documentStore.memory.set(stored,png);
 assert.throws(()=>gateway.read(a.f,docRequest),/无权/);
 assert.ok(db.prepare("SELECT id FROM operation_audit WHERE object_kind='cross_branch_clinical' AND json_extract(authority_snapshot,'$.documentVersionId')=? AND outcome_code='CROSS_BRANCH_QUERY_OK'").get(document.id));
 assert.throws(()=>service.authorizeCrossBranchRead(a.f,request),/无权/);
 assert.throws(()=>service.authorizeCrossBranchRead(a.d,{...request,scope:'plan'}),/无权/);
 assert.throws(()=>service.authorizeCrossBranchRead({...a.d,token:'invalid'},request),/登录/);
 db.prepare('UPDATE cross_branch_record_access SET revoked_at=?,revoked_by=?').run(now,manager);
 assert.throws(()=>service.authorizeCrossBranchRead(a.d,request),/无权/);
 db.prepare('UPDATE cross_branch_record_access SET revoked_at=NULL,revoked_by=NULL').run();
 db.prepare('UPDATE branch_staff_role SET revoked_at=?,revoked_by=?').run(now,manager);
 assert.throws(()=>service.authorizeCrossBranchRead(a.d,request),/无权/);
});
