 assert.throws(()=>service.command(a.m,{...input,patientId:999,requestKey:'wrong-patient'}),/不一致/);
 db.exec("CREATE TEMP TRIGGER fail_grant_audit BEFORE INSERT ON operation_audit WHEN NEW.object_kind='cross_branch_record_access' BEGIN SELECT RAISE(ABORT,'grant audit failure'); END");
 assert.throws(()=>service.command(a.m,input),/grant audit failure/);
 assert.equal(db.prepare('SELECT count(*) n FROM cross_branch_record_access').get().n,0);
 db.exec('DROP TRIGGER fail_grant_audit');
