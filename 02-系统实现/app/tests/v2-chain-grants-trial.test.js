 assert.equal(gateway.read(a.d,query).record.visit_id,a.v.id);
 assert.throws(()=>service.command(a.m,{...input,requestKey:'duplicate-grant'}),/已有有效授权/);
 assert.throws(()=>service.command(a.m,{...input,scope:'health'}),/提交号/);
 db.prepare("UPDATE branch_staff_role SET revoked_at=?,revoked_by=? WHERE branch_id=2 AND staff_id=? AND role_code='branch_manager'").run(now,manager,manager);
 assert.throws(()=>service.command(a.m,input),/无权/);
