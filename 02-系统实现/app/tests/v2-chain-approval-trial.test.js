'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {setup}=require('./helpers/v2-treatment');
const {installTrialSchema}=require('../src/v2/chain-schema-trial');
const {ChainApprovalTrial}=require('../src/v2/chain-approval-trial');
const {ChainClinicalQuery}=require('../src/v2/chain-clinical-query');
const {insert}=require('../src/v2/common');

test('来源与目标店不同负责人协作授权，权限失效和审计失败均不生效',t=>{
 const a=setup(t),db=a.db;installTrialSchema(db);
 const now=a.auth.now(),manager=a.auth.session(a.m.token).staff_id,dentist=a.auth.session(a.d.token).staff_id;
 const role=db.prepare("SELECT id FROM access_role WHERE code='manager'").get().id;
 const account=db.prepare("SELECT id,staff_id FROM user_account WHERE login_name='assistant'").get();
 const qualification=insert(db,'staff_role_qualification',{staff_id:account.staff_id,role_id:role,valid_from:now,valid_until:null,verified_by:manager,
  verification_basis:'隔离测试任职',revoked_at:null,revoked_by:null,revocation_reason:null,created_at:now});
 insert(db,'account_role',{account_id:account.id,role_id:role,qualification_id:qualification,granted_by:a.auth.session(a.m.token).account_id,
  granted_at:now,valid_until:null,grant_reason:'隔离测试授权',revoked_by:null,revoked_at:null,revocation_reason:null});
 const login=a.auth.login({username:'assistant',password:'Clinic123!'}),targetManager={token:login.token,csrf:login.csrf,role:'manager'};
 db.exec("INSERT INTO clinic_chain(id,name) VALUES(1,'演示'); INSERT INTO clinic_branch(id,chain_id,branch_code,name) VALUES(1,1,'A','一店'),(2,1,'B','二店'); UPDATE visit SET branch_id=1");
 const roleGrant=db.prepare("INSERT INTO branch_staff_role(branch_id,staff_id,role_code,valid_from,granted_by,granted_at,evidence) VALUES(?,?,?,'2026-10-01T00:00:00Z',?,?,'隔离')");
 roleGrant.run(1,manager,'branch_manager',manager,now);roleGrant.run(2,account.staff_id,'branch_manager',manager,now);roleGrant.run(2,dentist,'dentist',manager,now);
 const flow=new ChainApprovalTrial(a),gateway=new ChainClinicalQuery(a.auth,a.documentStore);
 const propose={action:'propose',sourceBranchId:1,targetBranchId:2,dentistId:dentist,patientId:1,visitId:a.v.id,scope:'record',
  validUntil:'2026-10-20T00:00:00Z',reason:'已核实患者同意转店查阅',requestKey:'source-proposal',commandVersion:1};
 const query={sourceBranchId:1,targetBranchId:2,patientId:1,visitId:a.v.id,scope:'record'};
 assert.throws(()=>gateway.read(a.d,query),/无权/);
 const proposal=flow.command(a.m,propose);assert.equal(flow.command(a.m,propose).replayed,true);
 assert.throws(()=>gateway.read(a.d,query),/无权/);
 const withdrawn=flow.command(a.m,{...propose,requestKey:'proposal-withdraw'});
 const withdraw={action:'withdraw',proposalId:withdrawn.id,reason:'患者撤回申请',requestKey:'withdraw-1',commandVersion:1};
 assert.throws(()=>flow.command(targetManager,withdraw),/无权/);
 flow.command(a.m,withdraw);assert.equal(flow.command(a.m,withdraw).replayed,true);
 assert.throws(()=>flow.command(targetManager,{action:'approve',proposalId:withdrawn.id,reason:'核对',requestKey:'withdraw-approve',commandVersion:1}),/已经处理/);
 const rejected=flow.command(a.m,{...propose,requestKey:'proposal-reject'});
 const rejection={action:'reject',proposalId:rejected.id,reason:'目标店暂不能接诊',requestKey:'reject-1',commandVersion:1};
 assert.throws(()=>flow.command(a.m,rejection),/无权/);
 db.exec("CREATE TEMP TRIGGER fail_reject_audit BEFORE INSERT ON operation_audit WHEN NEW.outcome_code='CROSS_BRANCH_REJECTED' BEGIN SELECT RAISE(ABORT,'reject audit failure'); END");
 assert.throws(()=>flow.command(targetManager,rejection),/reject audit failure/);db.exec('DROP TRIGGER fail_reject_audit');
 flow.command(targetManager,rejection);assert.equal(flow.command(targetManager,rejection).replayed,true);
 assert.throws(()=>flow.command(targetManager,{action:'approve',proposalId:rejected.id,reason:'核对',requestKey:'reject-approve',commandVersion:1}),/已经处理/);
 assert.equal(db.prepare('SELECT count(*) n FROM cross_branch_record_access').get().n,0);
 const visible=flow.list(targetManager,2).items;
 assert.equal(visible.find(x=>x.id===withdrawn.id).status,'已撤回');
 assert.equal(visible.find(x=>x.id===rejected.id).status,'已拒绝');
 assert.equal(visible.find(x=>x.id===proposal.id).status,'待确认');
 assert.throws(()=>flow.list(a.m,2),/无权/);
 assert.throws(()=>flow.list(a.f,1),/无权/);
 db.exec("INSERT INTO clinic_branch(id,chain_id,branch_code,name) VALUES(3,1,'C','三店')");
 roleGrant.run(3,account.staff_id,'branch_manager',manager,now);
 assert.deepEqual(flow.list(targetManager,3).items,[]);
 const approve={action:'approve',proposalId:proposal.id,reason:'目标店核实就诊需要',requestKey:'target-approval',commandVersion:1};
 assert.throws(()=>flow.command(a.m,approve),/无权/);
 roleGrant.run(2,manager,'branch_manager',manager,now);
 assert.throws(()=>flow.command(a.m,approve),/另一名负责人/);
 db.prepare("UPDATE branch_staff_role SET revoked_at=?,revoked_by=? WHERE branch_id=2 AND staff_id=? AND role_code='branch_manager'").run(now,manager,manager);
 db.prepare("UPDATE branch_staff_role SET revoked_at=?,revoked_by=? WHERE branch_id=1 AND staff_id=? AND role_code='branch_manager'").run(now,manager,manager);
 assert.throws(()=>flow.command(targetManager,approve),/来源店负责人权限已失效/);
 db.prepare("UPDATE branch_staff_role SET revoked_at=NULL,revoked_by=NULL WHERE branch_id=1 AND staff_id=? AND role_code='branch_manager'").run(manager);
 db.exec("CREATE TEMP TRIGGER fail_approval BEFORE INSERT ON operation_audit WHEN NEW.outcome_code='CROSS_BRANCH_APPROVED' BEGIN SELECT RAISE(ABORT,'approval audit failure'); END");
 assert.throws(()=>flow.command(targetManager,approve),/approval audit failure/);
 assert.equal(db.prepare('SELECT count(*) n FROM cross_branch_record_access').get().n,0);
 db.exec('DROP TRIGGER fail_approval');
 const accepted=flow.command(targetManager,approve);assert.equal(flow.command(targetManager,approve).replayed,true);
 assert.equal(flow.list(a.m,1).items.find(x=>x.id===proposal.id).status,'已确认');
 assert.equal(gateway.read(a.d,query).record.visit_id,a.v.id);
 assert.throws(()=>flow.command(targetManager,{...approve,requestKey:'approval-again'}),/已经处理/);
 assert.ok(db.prepare("SELECT id FROM operation_audit WHERE outcome_code='CROSS_BRANCH_APPROVED' AND json_extract(authority_snapshot,'$.proposalId')=?").get(proposal.id));
 assert.equal(db.prepare('SELECT granted_by FROM cross_branch_record_access WHERE id=?').get(accepted.id).granted_by,account.staff_id);
 const short=flow.command(a.m,{...propose,scope:'health',validUntil:'2026-10-19T02:00:00Z',requestKey:'short-proposal'});
 a.setClock('2026-10-19T02:01:00Z');
 const sourceNew=a.auth.login({username:'manager',password:'Clinic123!'}),targetNew=a.auth.login({username:'assistant',password:'Clinic123!'});
 const sourceCredentials={token:sourceNew.token,csrf:sourceNew.csrf,role:'manager'},targetCredentials={token:targetNew.token,csrf:targetNew.csrf,role:'manager'};
 assert.equal(flow.list(targetCredentials,2).items.find(x=>x.id===short.id).status,'已过期');
 assert.throws(()=>flow.command(targetCredentials,{action:'approve',proposalId:short.id,reason:'核对',requestKey:'expired-approve',commandVersion:1}),/截止时间已到/);
 assert.doesNotThrow(()=>flow.command(sourceCredentials,{action:'withdraw',proposalId:short.id,reason:'申请失效后撤回',requestKey:'expired-withdraw',commandVersion:1}));
});
